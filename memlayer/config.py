"""记忆层 · **唯一的参数来源**（§15.3「参数组当一个整体交付」）。

纪律（照抄设计文档，别在这里破例）：

1. **一次只调一个**，其余锁死，并把用过的参数组**记录在产物里**；
   ⇒ 实验产物必须把整个 `Params` 序列化进 JSON。
2. 第九轮之后，交付物**以 `D` 为中心**：`D → {γ_type, D_max, β, M, 语义层权重}` **外加** `N_max`。
   那些由 `D` 决定的量不在这里写死，见 `divergence.params_for()`。
3. `enable_play_edges` / `cross_scene_bridge` / `hebbian_on_retrieve` 是**安全开关**，
   默认全关 —— 它们分别对应 §17（玩梗边）、§17.5-checklist①（跨场景共用概念通道）、
   §16.5（可复现性验收要求"在冻结快照上跑"）。
"""

from __future__ import annotations

from dataclasses import dataclass, replace


@dataclass(frozen=True)
class Params:
    """一组参数 = 一次交付（§15.3）。所有字段都带单位/来源说明。"""

    # ---------- 阶段一：种子（§15.0，§16.7-⑥ 加了归一化与显式权重）----------
    w_relevance: float = 1.00    # ω₁ 词面/向量相关（由 lexicon.py 提供，已归一）
    w_importance: float = 0.60   # ω₂ 重要性（语义）
    w_salience: float = 0.80     # ω₃ 显著度 S₀
    w_recency: float = 0.60      # ω₄ 最近性（已在 [0,1]）
    seed_topk: int = 8           # 种子取 top-K
    seed_threshold: float = 0.05  # 种子准入门槛（z 归一后）
    # **边的增益门槛**：`ŵ·γ < min_gain` 的边压根不走。
    # 早期实验的结论：它比"阈值剪节点"更可控 —— 直接决定"多大的联想才算数"，
    # 而且**与记忆库规模无关**（增益只跟出度和边类型有关）。
    # 🔴 早期 修（代码审查指出）：这两个默认值原本是 `0.0` / `"global"`，
    #    而**所有实验和 4/5 个检索测试都显式传 `beta_mode="hop"`** ⇒
    #    `Params()` 的默认路径**从来没被跑过**，而它恰好是"扩散被剪掉 95%、行为≈空对照"的那一组。
    #    将来别人写 `retrieve(snap, q, 0.5)`（不传 params）会拿到"只回种子"的行为，且没有测试会报错。
    # ⚠️ 也别把这个值调大：它有**悬崖** —— 一旦超过 `γ_min / ⟨出度⟩`，扩散会整条归零
    #    （实测：出度 30、γ=0.4 时单边只分到 1.3%，阈值 0.02 ⇒ 激活 253 → 9）。
    #    `retrieval` 里对它加了与出度挂钩的上限保护（effective_min_gain）；
    #    正解是把它改成**相对量**（"至少分到平均单边份额的 x%"），列在 §12 的待办里。
    min_gain: float = 0.005

    # ---------- 阶段二：扩散 / 闸门（§15、§16）----------
    beta: float = 0.10           # ① 相对阈值：每轮剪掉 A < β·max(A)
    # ①的**口径**（早期实验发现：两种口径的效果天差地别，见设计说明）
    #   "global" = 按设计文档字面：每轮剪 A < β·max(全局 A)
    #   "hop"    = 按本跳增量剪：A_new < β·max(本跳新增)（与边增益同尺度）
    #   "seed"   = 按种子分剪：A < β·max(种子分)（跨跳稳定、与规模无关）
    # 为什么会有第二、第三种：种子分是 4 项加权和（量纲 ~O(1)），而一跳的贡献是
    #   A_j × ŵ × γ ≈ A_j / ⟨出度⟩ × γ ⇒ 全局口径下 β 的有效门槛会**随平均出度漂移**
    #   （出度 10 时一跳贡献只有 max 的 8%，直接被 0.1 的 β 剪光 = 扩散完全失效）。
    # 三种口径的取舍见项目设计说明。
    beta_mode: str = "hop"
    depth_max: int = 2           # ② 最大深度（D=0 时会被 divergence 压到 1）
    gamma_co_occur: float = 0.40  # ③ 每跳衰减（按边类型）
    gamma_derived: float = 0.80
    gamma_play: float = 0.20     # §17：玩梗边最低
    top_m: int = 8               # ⑤ 每跳只取 top-M 邻居
    n_max: int = 50              # ⑥ 总展开节点数硬上限
    #      ⚠️ 跑"爆炸测试"时必须放开它（§16.7-⑤），否则激活集合恒为常数、判据恒真

    # ---------- 🆕 第六道闸门「口径闸门」（§15.2-⑥，早期 发现 1 的修复）----------
    # 病灶（`早期实验` 实测）：阶段一（种子）是 4 项 z 归一的加权和，量纲 ~O(1)；
    #   阶段二（扩散）是 `A_j × ŵ × γ`，而 ŵ 被出度归一（⟨出度⟩ 30 时 ≈1/30）
    #   ⇒ 扩散分比种子分**小两个数量级**。后果：库里只要存在一个"同名的另一件事"
    #   （别的场景、同一个线索词），它作为种子**永远压在正确答案上面**（早期夹具上反复出现）。
    #   这是**排序口径**的缺陷，不是 `D` 的缺陷：调 `D` 完全不影响它。
    # 修法 = 两个乘子，都不改激活集合（只改"怎么读"，§16.2 的三条边界不冲突）：
    #   ① `stage2_weight`：阶段二整体折到阶段一的尺子上（各自的 top-1 → 1.0，再乘这个系数）；
    #   ② `cross_scene_rank_factor`：跨出 `seed_scene` 的节点在**排序**上打折
    #      （语义层节点 `scene=None` 豁免，与 §15-⑤ 保持一致）。
    # ⚠️ 两个都是**排序**参数：`cross_scene_rank_factor=1.0` + `stage2_weight=1.0` 即关掉这道闸门。
    stage2_weight: float = 0.80         # 扩散分的整体折扣（<1 = 同分时优先信种子）
    # 跨场景节点在排序上的惩罚（1.0 = 关掉）。**默认 0.1 的来历**：
    #   ① 结构性理由（主要）：本设计里跨场景的**情景层**节点**没有合法通道** ——
    #      `cross_scene_bridge=False` 掐断跨场景 co_occur，语义层（`scene=None`）另有豁免
    #      ⇒ 它们只可能是"线索词在别的场景里命中了另一件事"（§9.3 的"麦当劳那次 vs 游泳那次"）。
    #      这种命中在排序上就该显著落后，而不是靠一条边进来。
    #   ② 实测（`早期实验` 的"先验强度扫描"）：能把「题外压它」打到 0 的区间是
    #      `factor ≤ 0.20`（0.25 还不够）。默认取 0.1，留约 2.5× 余量。
    #   ⚠️ 这个区间是**夹具相关**的，别当普适阈值；换成别的库要重跑那张扫描表。
    cross_scene_rank_factor: float = 0.10  # 跨场景节点在排序上的惩罚（1.0 = 关掉）
    rank_eps: float = 1e-12             # 防御除零；正常路径下用不到

    # ---------- 发散度 D 的映射幅度（§16.1 一维旋钮驱动五个参数）----------
    d_gamma_span: float = 0.50   # D=0 时 γ 乘 (1−span)，D=1 时乘 1
    d_beta_span: float = 0.80    # D=0 时 β 乘 1，D=1 时乘 (1−span)
    d_topm_span: int = 12        # M 从 (top_m − span)/... 到 top_m
    d_depth_span: int = 1        # 深度在 depth_max 上再加 D·span
    semantic_w_low: float = 0.20  # D=0 时语义层节点的入场权重
    semantic_w_high: float = 1.00  # D=1
    play_min_d: float = 0.50     # §17：玩梗边只在 D ≥ 此值时允许被走到

    # ---------- 权重公式（§11–§13）----------
    # 通道权重 wᵢ，顺序与 types.CHANNELS 一致：(happy, angry, shame, hope, worry, anxiety, arousal)
    # ⚠️ 期待拆成 hope/worry 之后，原来 anticipation 的那一份权重（0.80）**分给了两条**，
    #    否则"期待相关"的权重会凭空翻倍（那是参数漂移，不是设计）。
    # `anxiety`（早期 深夜由 calm 改名；方向 = 越大越不安）⇒ 权重 0.80。
    channel_weights: tuple[float, ...] = (1.00, 1.00, 1.00, 0.40, 0.40, 0.80, 1.20)
    kappa: float = 1.00          # 持久性 = base_persist × (1 + κ·S₀)（§13.3，**唯一写法**）
    mu: float = 0.50            # 压缩   = 1 / (1 + μ/S₀)
    alpha_recency: float = 0.50  # 检索用 S_now = S₀ × recency^α（§16.7-①）
    recency_half_life_days: float = 7.0
    # ---------- 遗忘曲线的形状（§20）----------
    # "exponential" = `0.5^(t/h)`：**均匀遗忘**（危险率恒定，最终严格归零，没有长尾）
    # "power"       = `1/(1+t/τ)^β`：**艾宾浩斯式**（先掉得快、后面拖着长尾，永远不会真的到 0）
    # 🔴 早期 深夜**已切到幂律**（调用方提议试艾宾浩斯）：同一条大事"一年不复述"仍停在 active 档
    #   （0.355），而指数曲线会归零 —— 两曲线对比见项目实验记录。
    #   要退回指数：`Params(decay_curve="exponential")`（或改这一行）。
    decay_curve: str = "power"
    power_beta: float = 0.50    # β：尾巴有多粗（越小越"忘不掉"）
    power_tau: float = 1.0      # τ（天）：开始衰减的时间尺度
    modulator_lambda: float = 0.50  # 调制器倍率（§11.6-4：v1 用默认常量）
    # 🆕 「未完成/反刍」对编码强度的加成（Zeigarnik）。`0` = 关掉（与旧公式完全一致）。
    kappa_unfinished: float = 0.50

    # ---------- 🆕 复述时钟的"折扣"（§26.1，调用方 早期 提案）----------
    # 病灶（§24.9.1 实测）：检索命中只做两件事 —— `access_count += 1`、`last_access = now`；
    #   而 `recency` 的计时锚是 `max(created_at, last_access)`（lifecycle.recency_of）
    #   ⇒ **被碰一下就把遗忘时钟整根拨回原点，而且不分大小事**。
    #   后果：富者愈富明显高于通过线，而且对照臂显示**主要是由这一项造成**。
    #   这正是"没机会被提到的事被饿死"（§25.3 方向 B）。
    #
    # 调用方提案（原话）：「反复提起的事…根据其**权重**去**逐级递减**，最后**趋近于 0**，
    #   小事件不能因为反复提及就不会遗忘，因为其**权重远远达不到能和遗忘动态平衡的程度**」
    # ⇒ 落到本架构的准确形式：**拨回幅度被折扣**，折扣率 = `g(S₀) × h(access_count)`
    #   * `g(S₀) = clamp(S₀ / reset_weight_gate, 0, 1)` —— **权重闸门**：
    #     小事件的 `S₀` 达不到 gate ⇒ `g → 0` ⇒ **碰了也等于没碰**（仍按遗忘曲线衰减）；
    #     大事件的 `S₀` 过 gate ⇒ `g → 1` ⇒ 复述能维持 ⇒ **与遗忘达成动态平衡**（§19.4 的原设想，
    #     而且现在**只有大事达成得了** —— 这正是调用方那句话的形式化）。
    #   * `h(n) = 1 / (1 + n / reset_repeat_halflife)` —— **逐级递减**：
    #     碰得越多，单次拨回越少；`n → ∞` 时 `h → 0` ⇒ **重复本身无法无限维持**。
    # 有效锚点：`anchor = created_at + g·h · (last_access − created_at)`
    #   （`g·h = 1` 时退化为原来的全额重置；`= 0` 时等于"从没被碰过"）。
    # ⚠️ **默认关**：关掉时与旧行为**逐位相同**，所以已验收的 d_scan / explosion / fact_scan
    #   数字一个都不动（这是本项目的纪律：新机制一律 opt-in，见 `decay_curve` 的先例）。
    reset_discount_enabled: bool = False
    reset_weight_gate: float = 0.50      # S₀ 达到它，复述才"全额有效"
    # ⚠️ 早期 首轮实测修正：最初的写法把 `h(n)` 做成**与权重无关**（所有节点同一个 halflife），
    #   结果折扣**把小事件和大事一起削掉**（高档 gap 0.96 < 1，方向反了），
    #   而且只把富者愈富削掉一部分。原因：halflife 是共同瓶颈，权重根本没参与。
    #   设计说明是"**根据其权重**去逐级递减" ⇒ **递减的快慢本身必须由权重决定**：
    #     `halflife_eff = reset_repeat_halflife × g(S₀)`
    #   ⇒ 大事（g→1）的复述效果几乎不衰减（能被反复复述维持）；
    #     小事（g→0）的 halflife→0 ⇒ 一次复述就几乎无效 ⇒ **趋近于 0**（调用方要的）。
    reset_repeat_halflife: float = 20.0  # 权重满档时的复述半衰次数（会再乘 g(S₀)）
    # ⚠️ 早期 次轮实测修正：线性闸门 `g = S₀/gate` **分不开大小事** ——
    #   合成库 `S₀` 的分布是 min 0.069 / p33 0.42 / p50 0.54 / p90 1.13 / max 2.35，
    #   也就是**大小事只差约 4 倍**，而幂律遗忘曲线（β=0.5）本身又把差异压扁
    #   ⇒ 线性闸门下"小事够不着、大事够得着"这个区间**几乎不存在**（实测高档 gap 只有 1.19）。
    #   改用幂次闸门 `g = clamp(S₀/gate, 0, 1) ** reset_gate_power`：
    #   小事被平方/立方压到接近 0，大事（≥gate）封顶仍为 1 ⇒ **选择性陡增**。
    #   默认 1.0 = 退回线性（与首轮实验一致，便于对照）。
    reset_gate_power: float = 1.0

    # ---------- 🆕 §27 复述**累积**使用强度（调用方 早期 澄清后的主机制）----------
    # 设计说明：「我认为的是**重复提及会导致权重增加**，是**增加幅度逐级递减**」。
    # ⚠️ 这与 §14.3 的"`s0` 冻结"**不冲突**，因为冻结保护的是**观测量**（当时的事实）：
    #   * `s0`    = 当时有多重（由观测量算一次，永久冻结）；
    #   * `s_use` = 后来被想起过多少次、巩固了多少（**活的量**，与 `access_count` 同类）。
    #   有效显著度 `s_eff = s0 + s_use` ⇒ **"越提越生气"那类正反馈仍然被堵死**
    #   （情绪通道一个字不改），但"**反复回忆会被巩固**"这件事成立了。
    #
    # 增量（与 §26.1 的时钟折扣**共用**闸门与递减参数，它们在这里含义相同）：
    #   Δ = use_growth_rate × g(S₀)^p × h(n)
    #   * `g` 的闸门读 **`s0`（冻结的那份）** ⇒ 小事件**永远**进不了闸门 ⇒ 增量恒≈0
    #     ⇒ "**小事件不能因为反复提及就不会遗忘**"（调用方要求）成立；
    #   * `halflife_eff = reset_repeat_halflife × g` ⇒ 大事递减慢、小事递减快
    #     ⇒ "**根据其权重去逐级递减，最后趋近于 0**"（调用方要求）成立。
    # ⚠️ **默认关**（opt-in）：关掉时与旧实现逐位相同。
    use_growth_enabled: bool = False
    use_growth_rate: float = 0.05   # 单次复述的最大增量（大事、第一次）
    use_growth_cap: float = 1.00    # `s_use` 上限（最多把有效权重抬一档，防无限增长）
    # ⚠️ 早期 代码审查指出：**绝对上限 1.0 相对 `S₀` 偏大** ——
    #   合成库 `S₀` 中位只有 0.54，上限 1.0 意味着一个**中等**节点反复复述后
    #   有效权重能翻近 3 倍，与"小事不能靠重复变大事"的初衷相冲突。
    #   ⇒ 改为**相对上限**：`cap = min(use_growth_cap, ratio × s0)`。
    #   这样小事的天花板随它自己的权重一起低，大事仍然能涨到 1.0（被绝对上限卡住）。
    use_growth_cap_ratio: float = 0.50

    # ---------- 🆕 §19 随机检索器 / 随机跳（teleport，早期 实现）----------
    # 设计说明：「我们的记忆检索器是两个，一个是**关联检索器**，一个**随机检索器**，
    #   两种检索器都有**深度检索**，深度检索就是在检索的同时**随机到进行小范围检索**」
    # 身份确认（§19.2）：这就是 PageRank 的 **teleport / restart** ——
    #   扩散走到一半，以概率 `p` **瞬时传送**到图里远处的一个节点，再从那儿继续小范围扩散。
    #   它解决的正是 §18.3 量出来的 **F4**：`co_occur` 只能同场景 ⇒
    #   **库越大、可联想到的越少**（"越记越多、越联想不到"）。
    #
    # 🔴 **三条硬约束**（§19.2，实现里逐条落实）：
    #   1. **计入同一份预算**：随机跳一次能到任何地方，**深度限制对它天然无效**
    #      ⇒ 单独配额 `teleport_budget_ratio`（默认 10% 于 `n_max`），且**不许连续跳两次**；
    #   2. **只服务"闲聊/主动关怀"路**：调用方决定 —— 默认 `teleport_prob=0`（关），
    #      事实问答路**不许开**（§16.3 的路由）；
    #   3. **只读不写**：`retrieve()` 仍是纯函数，跳完不建边、不强化（§17 那个污染问题不会发生）。
    teleport_prob: float = 0.0            # 每跳传送概率（0 = 关；开了才有随机性）
    teleport_budget_ratio: float = 0.10   # 传送次数上限 = ratio × n_max（硬配额）

    # ---------- 🆕 §3.3/§20.3 生命周期状态（早期 实现）----------
    # 它决定的是"**要不要主动想起**"（主动关怀的候选），不是"还在不在"。
    # ⚠️ 阈值口径（**先定死，别事后调**）：
    #   ACTIVE   = `S_now ≥ state_active_s` **且**（被访问过 或 年龄 ≤ state_active_max_age_days）
    #   COLD     = `S_now ≥ state_cold_s`
    #   ARCHIVED = 其余（**节点仍在**，只是"想不起来、一提就想起来"）
    # 为什么 ACTIVE 要额外加"被访问过 / 还年轻"：§20.3 那条对策 ——
    #   幂律长尾会让十年前的旧事也停在 active 档（实测 S_now 0.355），
    #   于是"主动关怀"被远古记忆长期占据；状态必须**同时看**"权重"与"最近有没有被用到"。
    state_active_s: float = 0.50
    state_cold_s: float = 0.05
    state_active_max_age_days: float = 90.0

    # ---------- 安全开关（默认全关）----------
    enable_play_edges: bool = False   # §17：玩梗边整体禁用
    cross_scene_bridge: bool = False  # §17.5-①：跨场景"共用概念"通道，默认**掐断**
    hebbian_on_retrieve: bool = False  # §14.5：检索期改边；验收必须在冻结快照上跑
    retain_seeds: bool = True        # 种子永不被剪掉（它们是锚，§15.1①）
    edge_decay_rate: float = 0.02     # §14.5：**边也必须有衰减**，否则跑几千轮就饱和
    diffusion_enabled: bool = True    # False = **空对照**：只做阶段一（§15.4 的第一条对照臂）

    def variant(self, **overrides) -> "Params":
        """派生一组参数（对照实验用）。**只用来跑对照，不许当"事后微调"。**"""

        return replace(self, **overrides)

    def as_dict(self) -> dict:
        """序列化进产物 —— §15.3 的"参数必须记录在产物里"就是靠它。"""

        out: dict = {}
        for key, value in self.__dict__.items():
            out[key] = list(value) if isinstance(value, tuple) else value
        return out


# --------------------------------------------------------------------------- #
# 查询分路双档（§16.3 分路的落地，早期）
# --------------------------------------------------------------------------- #
def params_for_path(path: str, base: Params | None = None) -> Params:
    """按"查询路"取参数档。**只动种子分权重；闸门 / 发散度 / 遗忘一律不碰。**

    * `"companion"`（默认档）：现行默认 —— 种子分掺入 重要性/显著度/最近性，
      "什么值得被想起"参与排序（主动关怀 / 闲聊路的来源）；
    * `"fact"`（事实问答档）：种子分**砍掉叙事价值两项**（w_importance / w_salience → 0），
      只留 **相关性 + 最近性**。
      —— 15 个回忆场景 默认 10/15 → 事实档 **14/15**；且"最近那次"类查询的目标稳居第一
      （纯相关档只能排到二/三位，故保留最近性）。

    ⚠️ 这是**档位选择**（调用方按路选），不是在默认值上做微调；
    选档必须由调用方显式传入（路由约定见 §16.3）。
    """

    p = base or Params()
    if path in ("companion", "default"):
        return p
    if path == "fact":
        return p.variant(w_importance=0.0, w_salience=0.0)
    raise ValueError(f"未知查询路：{path!r}（可选 'fact' / 'companion'）")
